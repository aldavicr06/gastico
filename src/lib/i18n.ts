import type { Currency } from './format';

export type Lang = 'es' | 'en';

/** Language of the phone or browser, used until the user picks one. */
export function deviceLang(): Lang {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('es') ? 'es' : 'en';
  } catch {
    return 'es';
  }
}

/** Currency that goes with each language when the user has no data of their own yet. */
export function currencyFor(lang: Lang): Currency {
  return lang === 'en' ? 'USD' : 'CRC';
}

